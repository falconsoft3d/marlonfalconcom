export const IDIOMAS_CALENDARIO = [
  ['es', 'ES', 'Español'],
  ['en', 'EN', 'English'],
  ['ca', 'CA', 'Català'],
  ['ru', 'RU', 'Русский']
]

// Catalán y ruso solo existen en el calendario: se guardan aparte y, si no hay ninguno elegido,
// el calendario sigue el idioma de la web. Elegir ES o EN cambia el idioma de toda la web.
const CLAVE = 'calendario-idioma'
const SOLO_CALENDARIO = ['ca', 'ru']
const oyentes = new Set()
let propio = null
let leido = false

export function useIdiomaCalendario() {
  const { lang: sitio, setLang } = useIdioma()
  const [actual, setActual] = useState(null)

  useEffect(() => {
    oyentes.add(setActual)
    if (!leido) {
      leido = true
      // Un enlace con ?lang=ru (o ca, en, es) abre el calendario en ese idioma
      const enUrl = new URLSearchParams(window.location.search).get('lang')
      if (IDIOMAS_CALENDARIO.some(([codigo]) => codigo === enUrl)) {
        cambiar(enUrl)
      } else {
        try {
          const guardado = localStorage.getItem(CLAVE)
          propio = SOLO_CALENDARIO.includes(guardado) ? guardado : null
        } catch (e) {}
      }
    }
    setActual(propio)
    return () => oyentes.delete(setActual)
  }, [])

  const cambiar = (lang) => {
    propio = SOLO_CALENDARIO.includes(lang) ? lang : null
    try {
      if (propio) localStorage.setItem(CLAVE, propio)
      else localStorage.removeItem(CLAVE)
    } catch (e) {}
    if (!propio) setLang(lang)
    oyentes.forEach((oir) => oir(propio))
  }

  return { lang: actual || sitio, cambiar }
}

export default function useTextos() {
  const { lang } = useIdiomaCalendario()
  return { ...TEXTOS[lang], lang }
}
